/* ── PRODUCTS ── */
CREATE TABLE products (
    product_id   INT PRIMARY KEY IDENTITY(1,1),
    product_name NVARCHAR(255) NOT NULL,
    description  NVARCHAR(MAX),
    price        DECIMAL(10,2) NOT NULL,
    color        NVARCHAR(50),
    category_id  INT,
    brand_id     INT,
    rating       FLOAT         DEFAULT 0,
    stock        INT           DEFAULT 0,
    product_type VARCHAR(50),
    is_active    BIT           DEFAULT 1,
    created_at   DATETIME      DEFAULT GETDATE(),
    FOREIGN KEY (category_id) REFERENCES categories(category_id),
    FOREIGN KEY (brand_id)    REFERENCES brands(brand_id)
);
GO

/* ── PRODUCT SIZES (thêm sau step5) ── */
CREATE TABLE product_sizes (
    size_id    INT IDENTITY(1,1) PRIMARY KEY,
    product_id INT NOT NULL,
    size       NVARCHAR(10) NOT NULL,
    stock      INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_ps_product FOREIGN KEY (product_id)
        REFERENCES products(product_id) ON DELETE CASCADE,
    CONSTRAINT uq_ps UNIQUE (product_id, size)
);
GO

/* ── PRODUCT IMAGES ── */
CREATE TABLE product_images (
    image_id   INT PRIMARY KEY IDENTITY(1,1),
    product_id INT,
    image_url  NVARCHAR(255),
    is_primary BIT DEFAULT 0,
    FOREIGN KEY (product_id) REFERENCES products(product_id)
);
GO

/* ── REVIEWS ── */
CREATE TABLE reviews (
    review_id  INT PRIMARY KEY IDENTITY(1,1),
    product_id INT,
    user_id    INT,
    rating     INT  CHECK (rating BETWEEN 1 AND 5),
    comment    NVARCHAR(500),
    created_at DATETIME DEFAULT GETDATE(),
    FOREIGN KEY (product_id) REFERENCES products(product_id),
    FOREIGN KEY (user_id)    REFERENCES users(user_id)
);
GO

/* ── CART ── */
CREATE TABLE cart (
    cart_id    INT PRIMARY KEY IDENTITY(1,1),
    user_id    INT UNIQUE,
    created_at DATETIME DEFAULT GETDATE(),
    FOREIGN KEY (user_id) REFERENCES users(user_id)
);
GO

/* ── CART ITEMS (size thêm ở step6) ── */
CREATE TABLE cart_items (
    cart_item_id INT PRIMARY KEY IDENTITY(1,1),
    cart_id      INT,
    product_id   INT,
    quantity     INT           DEFAULT 1,
    size         NVARCHAR(10)  NOT NULL DEFAULT 'M',
    FOREIGN KEY (cart_id)    REFERENCES cart(cart_id),
    FOREIGN KEY (product_id) REFERENCES products(product_id)
);
GO

/* ── ORDERS (cancel_reason thêm ở step7) ── */
CREATE TABLE orders (
    order_id         INT PRIMARY KEY IDENTITY(1,1),
    user_id          INT,
    total_price      DECIMAL(10,2),
    status           NVARCHAR(50)  DEFAULT N'Pending',
    shipping_address NVARCHAR(255),
    receiver_name    NVARCHAR(100),
    receiver_phone   VARCHAR(20),
    payment_method   VARCHAR(50)   DEFAULT 'COD',
    payment_status   VARCHAR(50)   DEFAULT 'Unpaid',
    note             NVARCHAR(255),
    cancel_reason    NVARCHAR(500) NULL,
    created_at       DATETIME      DEFAULT GETDATE(),
    updated_at       DATETIME      DEFAULT GETDATE(),
    FOREIGN KEY (user_id) REFERENCES users(user_id)
);
GO

/* ── ORDER ITEMS (size thêm ở step7) ── */
CREATE TABLE order_items (
    order_item_id INT PRIMARY KEY IDENTITY(1,1),
    order_id      INT,
    product_id    INT,
    quantity      INT,
    price         DECIMAL(10,2),
    size          NVARCHAR(10) NOT NULL DEFAULT 'M',
    FOREIGN KEY (order_id)   REFERENCES orders(order_id),
    FOREIGN KEY (product_id) REFERENCES products(product_id)
);
GO

