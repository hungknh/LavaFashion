-- Cập nhật AVG rating cho sản phẩm
UPDATE products SET rating =
    (SELECT AVG(CAST(r.rating AS FLOAT))
     FROM reviews r WHERE r.product_id = products.product_id)
WHERE product_id IN (SELECT DISTINCT product_id FROM reviews);

